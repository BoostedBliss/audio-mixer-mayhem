import { VirtualDevice, VirtualChannelStrip } from '../types';

export const createDefaultChannels = (count: number): VirtualChannelStrip[] => {
  return Array.from({ length: count }, (_, i) => {
    const chNum = i + 1;
    const isMaster = chNum === 1 || chNum === 2;
    return {
      channelNumber: chNum,
      name: chNum === 1 ? 'Ch 1 (L)' : chNum === 2 ? 'Ch 2 (R)' : `Ch ${chNum}`,
      faderDb: isMaster ? 0 : -2.5,
      pan: chNum % 2 === 1 ? -15 : 15,
      isMuted: false,
      isSolo: false,
      isPhaseInverted: false,
      isHpfActive: false,
      peakDbL: -60,
      peakDbR: -60,
      rmsDbL: -60,
      rmsDbR: -60,
      isClipping: false,
      peakHoldL: -60,
      peakHoldR: -60,
      assignedGroup: 'None',
    };
  });
};

