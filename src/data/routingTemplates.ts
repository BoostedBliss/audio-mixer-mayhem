const LOCAL_STORAGE_PROFILES_KEY = 'loopcore_saved_user_profiles_v1';
const LOCAL_STORAGE_ACTIVE_PROFILE_KEY = 'loopcore_active_profile_id_v1';

/**
 * Loads user-saved custom profiles from LocalStorage
 */
export function loadUserProfiles(): RoutingProfile[] {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_PROFILES_KEY);
    if (!raw) return [];
    return JSON.parse(raw);
  } catch (err) {
    console.error('Failed to load user profiles from localStorage', err);
    return [];
  }
}

/**
 * Persists user profiles to LocalStorage
 */
export function saveUserProfiles(profiles: RoutingProfile[]): void {
  try {
    localStorage.setItem(LOCAL_STORAGE_PROFILES_KEY, JSON.stringify(profiles));
  } catch (err) {
    console.error('Failed to save user profiles to localStorage', err);
  }
}

/**
 * Gets currently active profile ID
 */
export function getActiveProfileId(): string | null {
  try {
    return localStorage.getItem(LOCAL_STORAGE_ACTIVE_PROFILE_KEY);
  } catch {
    return null;
  }
}

/**
 * Sets currently active profile ID
 */
export function setActiveProfileId(id: string | null): void {
  try {
    if (id) {
      localStorage.setItem(LOCAL_STORAGE_ACTIVE_PROFILE_KEY, id);
    } else {
      localStorage.removeItem(LOCAL_STORAGE_ACTIVE_PROFILE_KEY);
    }
  } catch {
    // Ignore storage issues
  }
}

/**
 * Creates a new profile object snapshot from a VirtualDevice
 */
export function createProfileFromDevice(
  device: VirtualDevice,
  name: string,
  description: string,
  category: ProfileCategory
): RoutingProfile {
  return {
    id: `profile-custom-${Date.now()}`,
    name,
    description: description || `Custom profile snapshot created on ${new Date().toLocaleDateString()}`,
    category,
    isTemplate: false,
    tag: 'Custom User Profile',
    icon: category === 'streaming' ? 'Tv' : category === 'podcasting' ? 'Radio' : category === 'music_production' ? 'Sliders' : 'Folder',
    createdAt: Date.now(),
    updatedAt: Date.now(),
    sampleRate: device.sampleRate,
    bufferSize: device.bufferSize,
    channelCount: device.channelCount,
    sources: JSON.parse(JSON.stringify(device.sources)),
    destinations: JSON.parse(JSON.stringify(device.destinations)),
    routes: JSON.parse(JSON.stringify(device.routes)),
    channels: JSON.parse(JSON.stringify(device.channels)),
    masterVolumeDb: device.masterVolumeDb,
    masterMuted: device.masterMuted,
    monitorVolumeDb: device.monitorVolumeDb,
    monitorMuted: device.monitorMuted,
  };
}

/**
 * Applies a profile or preset template to an existing VirtualDevice
 */
export function applyProfileToDevice(device: VirtualDevice, profile: RoutingProfile): VirtualDevice {
  return {
    ...device,
    sampleRate: profile.sampleRate,
    bufferSize: profile.bufferSize,
    channelCount: profile.channelCount,
    sources: JSON.parse(JSON.stringify(profile.sources)),
    destinations: JSON.parse(JSON.stringify(profile.destinations)),
    routes: JSON.parse(JSON.stringify(profile.routes)),
    channels: JSON.parse(JSON.stringify(profile.channels)),
    masterVolumeDb: profile.masterVolumeDb,
    masterMuted: profile.masterMuted,
    monitorVolumeDb: profile.monitorVolumeDb,
    monitorMuted: profile.monitorMuted,
  };
}
